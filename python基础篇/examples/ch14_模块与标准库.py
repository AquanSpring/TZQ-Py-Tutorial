# ---------------------------------------------------------------
# import 的两种常用姿势
# ---------------------------------------------------------------

import math

print(math.sqrt(16))    # 4.0 —— 平方根
print(math.pi)          # 3.141592653589793 —— 圆周率

from math import sqrt   # 单独导入，省掉前缀

print(sqrt(16))         # 4.0 —— 不用再写 math.


# ---------------------------------------------------------------
# 实用模块巡礼
# ---------------------------------------------------------------

import random

print(random.randint(1, 100))                  # 1~100 的随机整数（含两端）
print(random.choice(["石头", "剪刀", "布"]))     # 随机选一个

import time

print(time.time())     # 当前时间戳（从 1970 年到现在的秒数）
time.sleep(1)          # 程序暂停 1 秒（运行时会真的等 1 秒）
print("暂停结束")


# ---------------------------------------------------------------
# 动手：掷骰子模拟器
# ---------------------------------------------------------------

# 正文的交互版：
#     while True:
#         dice = random.randint(1, 6)
#         print(f"掷出了 {dice} 点")
#         again = input("再来一次？(y/n)：")
#         if again != "y":
#             break
# 下面把 input 换成一组固定回答，while + break 的骨架完全一样：
for again in ["y", "y", "n"]:
    dice = random.randint(1, 6)
    print(f"掷出了 {dice} 点")
    print(f"（假装用户回答了 {again}）")
    if again != "y":
        break


# ---------------------------------------------------------------
# 选学：if __name__ == "__main__":
# ---------------------------------------------------------------

# 直接运行本文件时，__name__ 的值就是 "__main__"；
# 被别的文件 import 时，它的值是模块名（文件名去掉 .py）。
print(__name__)          # __main__

if __name__ == "__main__":
    print("我是被直接运行的，不是被 import 的")
