# ---------------------------------------------------------------
# 字典的基本操作
# ---------------------------------------------------------------

student = {"name": "小明", "age": 18}

print(student["name"])        # 小明 —— 按键取值
student["score"] = 95         # 键不存在 → 新增键值对
student["age"] = 19           # 键已存在 → 修改值
del student["score"]          # 删除这个键值对
print(len(student))           # 2 —— 键值对的个数

# 键的硬性要求：必须是不可变类型。数字 / 字符串 / 元组都行，列表不行
ok = {"name": "小明", (1, 2): "元组当键也可以"}
print(ok[(1, 2)])             # 元组当键也可以

try:
    bad = {[1, 2]: "列表当键"}     # ❌ 列表是可变类型，不能当键
except TypeError as e:
    print("TypeError:", e)


# ---------------------------------------------------------------
# 还有几个字典方法
# ---------------------------------------------------------------

student = {"name": "小明", "age": 18}

student.update({"age": 19, "score": 95})    # 批量新增或修改
print(student)                              # {'name': '小明', 'age': 19, 'score': 95}

print(student.pop("score"))                 # 95 —— 取出并删掉这个键
print(student)                              # {'name': '小明', 'age': 19}

print(student.setdefault("city", "北京"))    # 北京 —— 键不存在就设上默认值
print(student.setdefault("name", "小红"))    # 小明 —— 键已存在则不改，直接返回原值

# clear() 清空整本字典。这里用另一本演示，免得把上面的 student 清掉
throwaway = {"a": 1, "b": 2}
throwaway.clear()
print(throwaway)                            # {}


# ---------------------------------------------------------------
# 安全访问：.get()
# ---------------------------------------------------------------

# ❌ 正文里的反面例子：键不存在会报 KeyError。用 try/except 接住看真实报错：
try:
    print(student["phone"])
except KeyError as e:
    print("KeyError:", e)

print(student.get("phone"))             # None
print(student.get("phone", "未填写"))    # 未填写 —— 第二个参数是默认值

print("age" in student)                 # True —— in 判断的是【键】是否存在
print("phone" in student)               # False


# ---------------------------------------------------------------
# 遍历字典
# ---------------------------------------------------------------

for key, value in student.items():
    print(key + "：" + str(value))

for name in student.keys():      # 只拿键
    print(name)

for value in student.values():   # 只拿值
    print(value)


# ---------------------------------------------------------------
# 实战：用字典计数
# ---------------------------------------------------------------

text = "hello"

counts = {}
for ch in text:
    counts[ch] = counts.get(ch, 0) + 1

print(counts)        # {'h': 1, 'e': 1, 'l': 2, 'o': 1}


# ---------------------------------------------------------------
# 集合：去重和判断利器
# ---------------------------------------------------------------

nums = [1, 2, 2, 3, 3, 3]

unique = set(nums)         # 列表转集合，重复的自动消失
print(unique)              # {1, 2, 3}

print(2 in unique)         # True —— 成员判断非常快
unique.add(4)              # 添加元素
print(unique)              # {1, 2, 3, 4}

print(list(set(nums)))     # [1, 2, 3] —— “去重后转回列表”的惯用法

# 必踩的坑：空花括号是【空字典】，不是空集合
a = {}          # 这是空字典！
b = set()       # 这才是空集合
c = {1, 2, 3}   # 有元素时，花括号才是集合

print(type(a))  # <class 'dict'> —— 注意不是 set
print(type(b))  # <class 'set'>
print(type(c))  # <class 'set'


# ---------------------------------------------------------------
# 集合真正好用的地方：集合运算
# ---------------------------------------------------------------

a = {1, 2, 3, 4}
b = {3, 4, 5}

print(a | b)    # {1, 2, 3, 4, 5} —— 并集：两边都算上
print(a & b)    # {3, 4}          —— 交集：两边都有
print(a - b)    # {1, 2}          —— 差集：在 a 里但不在 b 里
print(a ^ b)    # {1, 2, 5}       —— 对称差：只在一方出现


# ---------------------------------------------------------------
# 嵌套容器：列表装字典
# ---------------------------------------------------------------

students = [
    {"name": "小明", "score": 90},
    {"name": "小红", "score": 85},
    {"name": "小刚", "score": 77},
]

for stu in students:
    print(f"{stu['name']} 考了 {stu['score']} 分")

# 读法：students[0] 取出第一个字典，students[0]["name"] 再取出里面的值
print(students[0]["name"])     # 小明


# ---------------------------------------------------------------
# 选学：列表推导式
# ---------------------------------------------------------------

scores = [90, 85, 77, 100, 55]    # 最后一个是 55 分，留着看下面筛选的效果

bonus = []
for s in scores:
    bonus.append(s + 5)

print(bonus)    # [95, 90, 82, 105, 60]

bonus = [s + 5 for s in scores]
print(bonus)    # [95, 90, 82, 105, 60] —— 和上面的 for 循环完全等价

passed = [s for s in scores if s >= 60]
print(passed)    # [90, 85, 77, 100] —— 带 if 的筛选：55 分没及格，被筛掉了


# ---------------------------------------------------------------
# 选学：字典推导式与集合推导式
# ---------------------------------------------------------------

# 字典推导式：把分数映射成等级
raw = [90, 55, 77]
levels = {s: ("及格" if s >= 60 else "不及格") for s in raw}
print(levels)    # {90: '及格', 55: '不及格', 77: '及格'}

# 集合推导式：收集所有出现过的首字母（集合自动去重）
words = ["apple", "banana", "avocado"]
print(sorted({w[0] for w in words}))    # ['a', 'b'] —— 用 sorted 让输出顺序固定


# ---------------------------------------------------------------
# 顺带：any() 与 all()
# ---------------------------------------------------------------

# 和推导式很搭：它们吃的正是“一串 True / False”
# 这里换一组“全部及格”的分数，方便看出 all() 什么时候为 True
scores = [90, 85, 77, 100, 66]

print(any(s >= 100 for s in scores))    # True  —— 有没有一个满足
print(all(s >= 60 for s in scores))     # True  —— 是不是全都满足
print(all(s >= 80 for s in scores))     # False —— 有一个不满足就不行
