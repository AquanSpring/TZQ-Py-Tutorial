# ---------------------------------------------------------------
# if：条件成立才执行
# ---------------------------------------------------------------

age = 18

if age >= 18:
    print("你已成年")
    print("欢迎注册")

print("程序结束")


# ---------------------------------------------------------------
# else：两种情况，必走其一
# ---------------------------------------------------------------

age = 16

if age >= 18:
    print("你已成年")
else:
    print("你还未成年")


# ---------------------------------------------------------------
# elif：多种情况依次判断
# ---------------------------------------------------------------

score = 85

if score >= 90:
    print("优秀")
elif score >= 80:
    print("良好")
elif score >= 60:
    print("及格")
else:
    print("不及格")


# ---------------------------------------------------------------
# and、or、not：条件的组合
# ---------------------------------------------------------------

age = 20
has_ticket = True

if age >= 18 and has_ticket:
    print("可以入场")

vip = False
amount = 120

if vip or amount >= 99:
    print("免运费")

if not vip:
    print("开通会员享专属折扣")

b = 0
if b != 0 and 10 / b > 1:     # 左边为假，右边的 10 / b 压根不会算，所以不会报 ZeroDivisionError
    print("成立")

# 正文里的写法会停下来等你输入（直接按回车 = 空字符串 = 假值）：
#     name = input("你的名字：") or "游客"
# 下面用一组固定输入演示同一条规则，不需要你手动敲：
for raw in ["", "小明"]:
    name = raw or "游客"
    print("输入「" + raw + "」→ 名字是「" + name + "」")


# ---------------------------------------------------------------
# 嵌套：if 里面还能有 if
# ---------------------------------------------------------------

age = 20
has_ticket = True

if age >= 18:
    if has_ticket:
        print("可以入场")
    else:
        print("请先购票")
else:
    print("未满 18 岁禁止入场")

age = 20
tag = "成年" if age >= 18 else "未成年"
print(tag)    # 成年
