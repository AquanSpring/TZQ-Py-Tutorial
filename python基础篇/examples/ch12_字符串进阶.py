# ---------------------------------------------------------------
# 字符串也是序列
# ---------------------------------------------------------------

s = "Python"

print(s[0])       # P
print(s[-1])      # n —— 负索引照样有效
print(s[1:4])     # yth —— 切片含头不含尾
print(len(s))     # 6

for ch in s:
    print(ch)


# ---------------------------------------------------------------
# 字符串不可修改
# ---------------------------------------------------------------

s = "Python"

# ❌ 正文里的反面例子：字符串不支持修改。用 try/except 接住看真实报错：
try:
    s[0] = "J"
except TypeError as e:
    print("TypeError:", e)

# 想“改”字符串，只能创建一个新字符串：
s = "J" + s[1:]
print(s)         # Jython


# ---------------------------------------------------------------
# 常用方法：字符串的内置技能
# ---------------------------------------------------------------

s = "  Hello, Python  "

print(s.strip())                   # 去掉两端空格 → "Hello, Python"
print(s.strip().lower())           # 全变小写 → "hello, python"（方法可以链着用）
print(s.replace("Hello", "Hi"))    # 替换 → "  Hi, Python  "
print("python".upper())            # PYTHON —— 全大写

csv = "apple,banana,orange"
fruits = csv.split(",")
print(fruits)         # ['apple', 'banana', 'orange']

print("Py" in "Python")    # True —— in 也能判断子串

print("123".isdigit())             # True —— 全是数字字符才返回 True
print("hello world".find("wor"))   # 6 —— 子串首次出现的位置
print("hello world".find("xyz"))   # -1 —— 找不到返回 -1

parts = ["apple", "banana", "orange"]
print("-".join(parts))             # apple-banana-orange —— split 的逆操作

# 关键细节：这些方法都不会改变原字符串，而是返回一个新字符串
s = "  Hello, Python  "
s.strip()
print(s)               # 仍有两端空格 —— 原字符串没变
s = s.strip()          # 要写成 s = s.strip() 才真正更新变量
print(s)


# ---------------------------------------------------------------
# 转义字符：\n 和它的朋友们
# ---------------------------------------------------------------

print("第一行\n第二行")       # \n 换行
print("姓名\t成绩")           # \t 制表符，用于对齐
print("他说：\"你好\"")        # \" 在双引号字符串里再放双引号

text = """三引号字符串
可以原样保留
很多行的内容"""                    # 多行文本，不用自己拼 \n
print(text)

path = r"C:\new\folder"           # 字符串前加个 r：原始字符串
print(path)                       # C:\new\folder —— \ 原样保留


# ---------------------------------------------------------------
# 动手：整理用户输入
# ---------------------------------------------------------------

# 正文的交互版：
#     answer = input("你同意吗？(yes/no)：")
# 下面换成几种“不规范输入”，演示 strip() + lower() 的作用：
for answer in [" YES ", "Yes", "no"]:
    answer = answer.strip().lower()

    if answer == "yes":
        print(f"输入「{answer}」→ 好的，继续")
    else:
        print(f"输入「{answer}」→ 已取消")


# ---------------------------------------------------------------
# 选学：一次读入多个值（与 input 配合）
# ---------------------------------------------------------------

# 正文的交互版：
#     a, b = input("请输入两个数，用空格隔开：").split()
# 下面用固定的一行输入演示同样的流程：
line = "3 5"
a, b = line.split()
print(a, b)          # 3 5 —— 注意，它们现在还是【字符串】
print(a + b)         # 35 —— 字符串相加是拼接，不是 8

a, b = int(a), int(b)
print(a + b)         # 8 —— 转成数字之后，才是真的加法
