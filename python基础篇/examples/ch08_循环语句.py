# ---------------------------------------------------------------
# while：条件成立就一直做
# ---------------------------------------------------------------

count = 1

while count <= 5:
    print("这是第 " + str(count) + " 次循环")
    count += 1

print("循环结束")


# ---------------------------------------------------------------
# for 与 range：按次数循环
# ---------------------------------------------------------------

for i in range(5):
    print(i)

# range 的三种写法（正文表格）。list() 第 10 章才学，这里只是把生成的数列显示出来
print(list(range(5)))          # [0, 1, 2, 3, 4]
print(list(range(1, 6)))       # [1, 2, 3, 4, 5]
print(list(range(1, 10, 2)))   # [1, 3, 5, 7, 9]
print(list(range(5, 0, -1)))   # [5, 4, 3, 2, 1] —— 步长可以是负数


# ---------------------------------------------------------------
# break 与 continue：控制循环走向
# ---------------------------------------------------------------

for i in range(1, 6):
    if i == 3:
        break        # 换成 continue 对比效果
    print(i)


# ---------------------------------------------------------------
# 嵌套循环：循环里套循环
# ---------------------------------------------------------------

for i in range(1, 4):
    line = ""
    for j in range(1, 4):
        line = line + str(i) + "×" + str(j) + "  "
    print(line)

# 动手改一改：内层改成 range(1, i + 1)，就得到九九乘法表的三角形
print("--- 三角形（九九乘法表的结构）---")
for i in range(1, 10):
    line = ""
    for j in range(1, i + 1):
        line = line + str(j) + "×" + str(i) + "=" + str(i * j) + "  "
    print(line)
