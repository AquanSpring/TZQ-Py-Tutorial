# ---------------------------------------------------------------
# 让程序开始“算”
# ---------------------------------------------------------------

price = 5
count = 3
total = price * count    # 右边是一个表达式，算出 15 赋给 total
print(total)             # 15


# ---------------------------------------------------------------
# 算术运算符（正文表格里的 7 个，建议先口算、再运行对答案）
# ---------------------------------------------------------------

print(7 + 2)      # 9
print(7 - 2)      # 5
print(7 * 2)      # 14
print(7 / 2)      # 3.5   —— / 的结果永远是浮点数
print(7 // 2)     # 3     —— 整除，只留整数部分
print(7 % 2)      # 1     —— 取余
print(7 ** 2)     # 49    —— 幂

print(10 / 2)     # 5.0   —— 注意不是 5
print(123 % 10)   # 3     —— % 的实用场景：提取个位
print(-7 // 2)    # -4    —— 负数是“向下取整”，不是简单扔掉小数部分


# ---------------------------------------------------------------
# 运算优先级
# ---------------------------------------------------------------

print(2 + 3 * 4)     # 14，先乘后加
print((2 + 3) * 4)   # 20，括号改变顺序


# ---------------------------------------------------------------
# 字符串也能“运算”
# ---------------------------------------------------------------

first = "Hello, "
second = "World!"
print(first + second)    # Hello, World!  —— + 是拼接

print("-" * 20)          # -------------------- —— * 是重复
print("Ha" * 3)          # HaHaHa


# ---------------------------------------------------------------
# 比较运算符：结果是“真 / 假”
# ---------------------------------------------------------------

age = 18
print(age >= 18)    # True
print(age == 20)    # False

# 连写比较：等价于 age >= 18 and age <= 60，判断“区间”时非常好用
print(18 <= age <= 60)    # True


# ---------------------------------------------------------------
# 简写运算符：+= 家族
# ---------------------------------------------------------------

count = 0
count += 1    # 等价于 count = count + 1，count 变成 1
count += 1    # count 变成 2
print(count)  # 2


# ---------------------------------------------------------------
# 一个著名的坑：浮点数误差
# ---------------------------------------------------------------

print(0.1 + 0.2)               # 0.30000000000000004 —— 不是 0.3，但这不是 bug
print(round(0.1 + 0.2, 2))     # 0.3 —— 用 round() 保留到指定位数
print(round(2.5), round(3.5))  # 2 4 —— round() 是“四舍六入五成双”，不是四舍五入
