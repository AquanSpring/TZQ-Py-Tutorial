# -*- coding: utf-8 -*-
"""第 4 章 代码的基本结构与规则 —— 章节示例（不含「本章挑战作业」的答案）

把本章正文里出现过的代码按顺序整理在一起，可以直接运行对照。
用法：python ch04_代码的基本结构与规则.py

说明：正文为了演示报错，故意写错了几行。本文件把它们做了区分处理：
      · 运行时才报错的（如 Print 大写）——用 try/except 接住，让你看到真实报错；
      · 语法就不合法的（如中文括号）——只能整行注释掉，因为语法错误会让
        整个文件都无法运行。
"""

# ---------------------------------------------------------------
# 规则一：代码自上而下，逐行执行
# ---------------------------------------------------------------

print("我先执行")
print("我后执行")
print("我最后执行")

# 动手改一改：把上面三行调换位置再运行，体会“书写顺序就是执行顺序”。


# ---------------------------------------------------------------
# 规则二：缩进（Indentation）即语法
# ---------------------------------------------------------------

age = 18

if age >= 18:
    print("你已成年")      # 缩进了 4 格：属于 if，条件成立才执行
    print("欢迎注册")      # 缩进了 4 格：属于 if，条件成立才执行

print("我不受 if 控制")     # 没有缩进：不属于 if，总会执行

# 动手改一改：把 age 改成 16，前两行就消失了。

print("--- 把 age 改成 16 之后 ---")
age = 16

if age >= 18:
    print("你已成年")
    print("欢迎注册")

print("我不受 if 控制")


# ---------------------------------------------------------------
# 规则三：注释——写给人看的说明
# ---------------------------------------------------------------

# 这一行是注释，不会被执行
print("Hello, Python!")  # 这也是注释，可以写在代码后面


# ---------------------------------------------------------------
# 规则四之一：严格区分大小写
# ---------------------------------------------------------------

print("Hello")   # ✅ 正确

# ❌ 下面这行会报 NameError：print 的 p 不能大写。
#    用 try/except 接住它，让你看到真实的报错信息：
try:
    Print("Hello")
except NameError as e:
    print("NameError:", e)


# ---------------------------------------------------------------
# 规则四之二：符号必须是英文半角
# ---------------------------------------------------------------

# ❌ 下面两行是正文里的反面例子，但它们是【语法错误】——
#    留在文件里会导致整个文件跑不起来，所以必须注释掉。
#
#     print（"Hello"）    # ❌ 用了中文括号（）
#     print(“Hello”)      # ❌ 用了中文引号“”
#
#    报错信息会类似：
#      SyntaxError: invalid character '（' (U+FF08)

print("你好，世界")   # ✅ 中文出现在引号内部，完全没问题
