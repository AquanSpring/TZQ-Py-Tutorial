# ---------------------------------------------------------------
# 定义与调用
# ---------------------------------------------------------------

def greet():
    print("你好！")
    print("欢迎学习 Python")

greet()     # 调用一次，执行一次
greet()

# pass 什么都不做，专门用来撑住还没写的语法结构
def todo():
    pass          # 还没想好怎么写，先占个位，保证代码能运行


# ---------------------------------------------------------------
# 参数：给函数传数据
# ---------------------------------------------------------------

def greet(name):
    print("你好，" + name + "！")

greet("小明")     # 你好，小明！
greet("小红")     # 你好，小红！

# 带默认值的参数：不传就用默认，传了就覆盖
def greet(name, greeting="你好"):
    print(greeting + "，" + name + "！")

greet("小明")               # 你好，小明！
greet("小明", "早上好")      # 早上好，小明！

# 关键字参数：指名道姓地传，顺序随意
greet(greeting="早上好", name="小明")    # 早上好，小明！


# ---------------------------------------------------------------
# 返回值：把结果交回去
# ---------------------------------------------------------------

def add(a, b):
    return a + b

result = add(3, 5)     # 函数算出 8，“交回”给调用处，存进 result
print(result)          # 8

# return 和 print 是两回事 —— 新手最容易混淆的地方
def bad_add(a, b):
    print(a + b)        # 只打印，没有返回

x = bad_add(3, 5)       # 屏幕上显示 8，但 x 是 None！
print(x)                # None

# return 可以一次返回多个值（其实是打包成元组），配合解包接收
def min_max(nums):
    return min(nums), max(nums)

low, high = min_max([3, 1, 4, 1, 5])
print(low, high)        # 1 5


