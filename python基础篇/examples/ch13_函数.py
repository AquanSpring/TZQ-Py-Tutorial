# ❌ 正文里的反面例子：函数内部定义的变量，外面看不到。
#    用 try/except 接住它，让你看到真实的 NameError：
try:
    print(inner)
except NameError as e:
    print("NameError:", e)


# ---------------------------------------------------------------
# 动手：写一个判断偶数的函数
# ---------------------------------------------------------------

def is_even(n):
    return n % 2 == 0

print(is_even(4))     # True
print(is_even(7))     # False

# 返回布尔值的函数常用 is_ 前缀命名，读起来像一句话：“4 是偶数吗？”
