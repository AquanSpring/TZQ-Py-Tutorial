# ---------------------------------------------------------------
# 什么是变量
# ---------------------------------------------------------------

name = "小明"    # 把字符串 "小明" 贴上 name 这个标签
age = 18         # 把整数 18 贴上 age 这个标签

print(name)      # 小明
print(age)       # 18

score = 60
score = score + 40    # 先算右边的 60 + 40，再把结果 100 赋回 score
print(score)          # 100


# ---------------------------------------------------------------
# 常用的数据类型
# ---------------------------------------------------------------

print(type(18))         # <class 'int'>
print(type(3.14))       # <class 'float'>
print(type("hello"))    # <class 'str'>
print(type(True))       # <class 'bool'>

# 整数的几种写法：0b 二进制、0o 八进制、0x 十六进制，下划线只是给人看的
print(0b1010)       # 10
print(0o17)         # 15
print(0xFF)         # 255
print(1_000_000)    # 1000000
print(type(0xFF))   # <class 'int'> —— 写法变了，类型没变


# ---------------------------------------------------------------
# 类型转换：在类型之间搭桥
# ---------------------------------------------------------------

# ❌ 正文里的反面例子：字符串和整数不能直接相加。
#    用 try/except 接住，让你看到真实的 TypeError：
try:
    print("5" + 5)
except TypeError as e:
    print("TypeError:", e)

print(int("5"))        # 字符串 → 整数，得到 5
print(float("3.14"))   # 字符串 → 浮点数，得到 3.14
print(str(100))        # 整数 → 字符串，得到 100
print(type(str(100)))  # 用 type() 验证它真的是字符串：<class 'str'>

# 一条规律：每个类型名都能当转换函数用
print(bool(""))        # False —— 空字符串是假值
print(list("abc"))     # ['a', 'b', 'c']
print(tuple([1, 2]))   # (1, 2)
print(set([1, 1, 2]))  # {1, 2} —— 顺便去重了

age = "18"          # 此时 age 是字符串
age = int(age)      # 转换成整数
print(age + 1)      # 19 ✅

age = 18
print("我今年 " + str(age) + " 岁")    # 我今年 18 岁
