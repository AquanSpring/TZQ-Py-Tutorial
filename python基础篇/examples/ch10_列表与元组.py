# ---------------------------------------------------------------
# 一个变量装下所有成绩
# ---------------------------------------------------------------

scores = [90, 85, 77, 100, 66]
print(scores)        # [90, 85, 77, 100, 66]


# ---------------------------------------------------------------
# 用索引访问：从 0 开始数
# ---------------------------------------------------------------

scores = [90, 85, 77, 100, 66]

print(scores[0])     # 90 —— 第一个元素
print(scores[3])     # 100
print(scores[-1])    # 66 —— 负数表示倒数

# 索引越界会报 IndexError，只有 5 个元素却访问 scores[5]：
try:
    print(scores[5])
except IndexError as e:
    print("IndexError:", e)


# ---------------------------------------------------------------
# 遍历：配合 for 逐个处理
# ---------------------------------------------------------------

for s in scores:
    print(s)

for i, s in enumerate(scores):
    print(f"第 {i + 1} 个成绩是 {s}")

names = ["小明", "小红"]
scores2 = [90, 85]

for name, score in zip(names, scores2):
    print(f"{name}：{score} 分")


# ---------------------------------------------------------------
# 增、删、改
# ---------------------------------------------------------------

scores = [90, 85, 77]

scores.append(100)      # 末尾添加 → [90, 85, 77, 100]
scores.insert(0, 60)    # 插到索引 0 的位置 → [60, 90, 85, 77, 100]
scores[1] = 86          # 修改 → [60, 86, 85, 77, 100]
scores.remove(77)       # 按值删除 → [60, 86, 85, 100]
last = scores.pop()     # 取出并返回最后一个元素 → scores 变 [60, 86, 85]，last 是 100

print(scores)           # [60, 86, 85]
print(last)             # 100

a = [1, 2, 3]
b = [4, 5]

print(a + b)      # [1, 2, 3, 4, 5] —— 拼接，产生一个新列表
a.extend(b)       # 把 b 的元素逐个塞进 a，效果类似 a = a + b；但 extend 是原地修改
print(a)          # [1, 2, 3, 4, 5]


# ---------------------------------------------------------------
# 切片：取一段
# ---------------------------------------------------------------

scores = [90, 85, 77, 100, 66]

print(scores[1:3])    # [85, 77] —— 索引 1 到 2，不含 3
print(scores[:2])     # [90, 85] —— 从头开始取
print(scores[2:])     # [77, 100, 66] —— 一直取到结尾

print(scores[::2])    # [90, 77, 66] —— 第三个参数是步长，每两个取一个
print(scores[::-1])   # [66, 100, 77, 85, 90] —— 步长为 -1，整个列表倒过来

# 重要细节：赋值不是复制。b = scores 只是给同一个列表多贴了一个标签
b = scores
b.append(999)
print(scores)         # [..., 999] —— 通过 b 改的，scores 看得一清二楚

# 想要真正独立的副本，用切片：
c = scores[:]
c.append(1000)
print(scores)         # 末尾没有 1000 —— 说明 c 是独立副本
print(c)              # 末尾有 1000


# ---------------------------------------------------------------
# 常用统计与成员判断
# ---------------------------------------------------------------

scores = [90, 85, 77, 100, 66]

print(len(scores))    # 5    个数
print(sum(scores))    # 418  总和
print(max(scores))    # 100  最大
print(min(scores))    # 66   最小
print(sum(scores) / len(scores))    # 83.6 平均分

print(100 in scores)    # True
print(59 in scores)     # False


# ---------------------------------------------------------------
# 排序：sort 与 sorted
# ---------------------------------------------------------------

scores = [90, 85, 77, 100, 66]

scores.sort()                  # 原地排序，直接改自己
print(scores)                  # [66, 77, 85, 90, 100]

scores.sort(reverse=True)      # 倒序
print(scores)                  # [100, 90, 85, 77, 66]

new_list = sorted(scores)      # 不动原列表，返回一个排好的新列表
print(new_list)                # [66, 77, 85, 90, 100] —— 新列表

scores.reverse()               # 只把现有顺序整个颠倒，不做比较排序
print(scores)                  # [66, 77, 85, 90, 100]


# ---------------------------------------------------------------
# 选学：按“规则”排序（key= 与 lambda）
# ---------------------------------------------------------------

words = ["banana", "kiwi", "apple"]
print(sorted(words, key=len))     # ['kiwi', 'apple', 'banana'] —— 按长度排

nums = [-5, 3, -1, 4]
print(sorted(nums, key=abs))      # [-1, 3, 4, -5] —— 按绝对值排

pairs = [(2, "b"), (1, "c"), (3, "a")]
print(sorted(pairs, key=lambda p: p[1]))   # [(3, 'a'), (2, 'b'), (1, 'c')] —— 按第二个元素排


# ---------------------------------------------------------------
# 元组：不可修改的列表
# ---------------------------------------------------------------

point = (3, 5)

print(point[0])       # 3 —— 访问没问题

# ❌ 正文里的反面例子：元组创建后不能修改。用 try/except 接住看真实报错：
try:
    point[0] = 10
except TypeError as e:
    print("TypeError:", e)

# 解包：一次把元组里的值分别赋给多个变量
x, y = (3, 5)
print(x, y)           # 3 5
